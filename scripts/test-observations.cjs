const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
require.extensions['.ts'] = function (module, file) {
  module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText, file)
}
const {createInitialState} = require('../src/data/scenarios.ts')
const {applyObservation} = require('../src/engine/observations.ts')
const state = createInitialState('surge')
const now = new Date().toISOString()
const c = {id:'e1',kind:'crossing',from:'external',to:'entry',count:7,source:'synthetic_gate',at:now}
const r1 = applyObservation(state,c)
assert.equal(r1.accepted,true)
assert.equal(r1.next.zones.entry.occupancy,state.zones.entry.occupancy+7)
assert.equal(state.zones.entry.occupancy,48,'original state unchanged')
const r2 = applyObservation(r1.next,{...c,id:'e2',kind:'crossing',from:'entry',to:'queueA',count:5})
assert.equal(r2.next.zones.entry.occupancy,50)
assert.equal(r2.next.zones.queueA.occupancy,239)
const r3 = applyObservation(r2.next,{id:'s1',kind:'correction',zoneId:'queueA',observedCount:450,reason:'Staff count from observation',source:'staff',at:now})
assert.equal(r3.accepted,true)
assert.equal(r3.next.zones.queueA.occupancy,450,'do not hide over-capacity readings')
assert.match(r3.message,/exceeded/)
const r4 = applyObservation(r3.next,{...c,id:'e4',from:'queueA',to:'external',count:2})
assert.equal(r4.accepted,false,'reject unconfigured crossing')
console.log('OK: observation updates, corrections, immutability, overload and crossing validation')
